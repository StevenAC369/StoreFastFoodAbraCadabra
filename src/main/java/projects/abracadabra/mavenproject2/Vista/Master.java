    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
       try {
            if (ServiciosUsuario.Ingresar(jTextField1.getText(), new String(jPasswordField1.getPassword()))) {
                ClienteActivo.username = jTextField1.getText();
                Inicio inicio = new Inicio();
                inicio.setLocationRelativeTo(null);
                inicio.setVisible(true);
                dispose();
            } else {
                JOptionPane.showMessageDialog(this, "Credenciales incorrectas", "Inicio de sesión",
                    JOptionPane.ERROR_MESSAGE);
            }
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "No se pudo verificar el usuario: " + ex.getMessage(),
                "Error de conexión", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

